"""Pydantic schemas for Travel Payment Gateway requests and responses."""

from datetime import datetime
from decimal import Decimal
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator
from app.models import TransactionStatus


class PaymentCreate(BaseModel):
    """Schema for online payment authorization creation."""
    amount: Decimal = Field(..., gt=0, decimal_places=2, description="Payment amount (greater than 0)")
    currency: str = Field(..., min_length=3, max_length=3, description="3-letter ISO-4217 currency code")
    description: Optional[str] = Field(None, max_length=255, description="Transaction description or receipt note")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Travel context (e.g. flight, seat)")
    auto_authorize: bool = Field(True, description="If True, moves immediately to AUTHORIZED. If False, remains PENDING.")

    @field_validator("currency")
    @classmethod
    def normalize_currency(cls, v: str) -> str:
        return v.upper().strip()


class PaymentCaptureRequest(BaseModel):
    """Optional payload for capture requests."""
    amount: Optional[Decimal] = Field(None, gt=0, decimal_places=2, description="Optional capture amount for partial capture")
    reason: Optional[str] = Field(None, max_length=255, description="Capture operational reason/notes")


class OfflineTransactionItem(BaseModel):
    """Individual offline transaction stored during low/no connectivity inflight operation."""
    id: Optional[str] = Field(None, description="Optional client-generated UUID for the offline transaction")
    idempotency_key: str = Field(..., min_length=1, max_length=128, description="Unique client-generated idempotency key")
    amount: Decimal = Field(..., gt=0, decimal_places=2, description="Amount transacted offline")
    currency: str = Field(..., min_length=3, max_length=3, description="3-letter ISO-4217 currency code")
    status: TransactionStatus = Field(
        default=TransactionStatus.CAPTURED,
        description="Offline transactions typically sync as CAPTURED (direct sale) or AUTHORIZED"
    )
    description: Optional[str] = Field(None, max_length=255)
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict)
    offline_created_at: Optional[datetime] = Field(None, description="Timestamp recorded on POS terminal clock")

    @field_validator("currency")
    @classmethod
    def normalize_currency(cls, v: str) -> str:
        return v.upper().strip()


class OfflineBatchSyncRequest(BaseModel):
    """Batch payload containing offline transactions uploaded upon reconnect (e.g. landing at gate)."""
    batch_id: Optional[str] = Field(None, description="Optional batch identifier generated by client terminal")
    flight_id: Optional[str] = Field(None, description="Flight number/code (e.g. MO-421)")
    terminal_id: Optional[str] = Field(None, description="POS Terminal Hardware ID")
    transactions: List[OfflineTransactionItem] = Field(..., description="Array of offline transactions")


class OfflineBatchItemResult(BaseModel):
    idempotency_key: str
    transaction_id: Optional[str] = None
    status: str = Field(..., description="SYNCED | DUPLICATE_SKIPPED | ERROR")
    message: Optional[str] = None


class OfflineBatchSyncResponse(BaseModel):
    """Response summary for offline batch processing."""
    batch_id: str
    total_received: int
    processed: int
    duplicates_skipped: int
    errors: int
    results: List[OfflineBatchItemResult]


class TransactionResponse(BaseModel):
    """Standard representation of a Transaction in the gateway."""
    model_config = ConfigDict(from_attributes=True)

    id: str
    idempotency_key: str
    amount: Decimal
    currency: str
    status: TransactionStatus
    description: Optional[str] = None
    metadata: Optional[Dict[str, Any]] = None
    created_at: datetime
    updated_at: datetime


class ReconciliationStatusSummary(BaseModel):
    status: TransactionStatus
    count: int
    total_amount: Decimal


class ReconciliationCurrencySummary(BaseModel):
    currency: str
    count: int
    total_amount: Decimal
    breakdown_by_status: Dict[str, Decimal]


class ReconciliationResponse(BaseModel):
    """Back-office financial reconciliation overview."""
    generated_at: datetime
    total_transactions: int
    total_volume: Decimal
    by_status: List[ReconciliationStatusSummary]
    by_currency: List[ReconciliationCurrencySummary]
